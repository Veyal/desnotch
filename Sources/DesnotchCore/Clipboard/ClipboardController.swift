import AppKit
import Combine
import Foundation

public struct ClipboardEntry: Identifiable, Equatable, Sendable {
    public let id: UUID
    public let text: String
    public let capturedAt: Date

    public init(id: UUID = UUID(), text: String, capturedAt: Date = Date()) {
        self.id = id
        self.text = text
        self.capturedAt = capturedAt
    }

    /// A single safe display line. The original text remains untouched for copying,
    /// while controls and bidirectional overrides cannot spoof the always-visible UI.
    public var preview: String {
        var scalars = String.UnicodeScalarView()
        var previousWasSpace = false
        var truncated = false
        for scalar in text.unicodeScalars {
            if scalars.count >= Self.previewScalarLimit {
                truncated = true
                break
            }
            let isBidiControl = (0x202A...0x202E).contains(scalar.value)
                || (0x2066...0x2069).contains(scalar.value)
                || scalar.value == 0x200E || scalar.value == 0x200F
            let isSpacingControl = CharacterSet.whitespacesAndNewlines.contains(scalar)
                || CharacterSet.controlCharacters.contains(scalar)
            if isBidiControl || isSpacingControl {
                if !previousWasSpace { scalars.append(" ") }
                previousWasSpace = true
            } else {
                scalars.append(scalar)
                previousWasSpace = false
            }
        }
        let result = String(scalars).trimmingCharacters(in: .whitespacesAndNewlines)
        guard !result.isEmpty else { return "Text" }
        // Mark the memory-bound cut so a wide pill never ends a row mid-word with no sign
        // of truncation (a narrow row still tail-truncates on its own).
        return truncated ? result + "\u{2026}" : result
    }

    /// Scalar cap for `preview` (a memory/display bound, not the visible width).
    static let previewScalarLimit = 72
}

/// A bounded, opt-in clipboard pocket for recent plain text.
///
/// Content never leaves memory or survives app exit. The controller checks only
/// `changeCount` on its low-frequency timer, reads data only after a real change,
/// rejects oversized values, and skips the pasteboard markers used by password
/// managers and transient-copy tools.
@MainActor
public final class ClipboardController: ObservableObject {
    public static let maxEntries = 8
    public static let maxTextBytes = 16 * 1024

    @Published public private(set) var entries: [ClipboardEntry] = []
    @Published public private(set) var copiedEntryID: UUID?

    private static let privateTypes = Set([
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ])

    private let pasteboard: NSPasteboard
    private let settings: SettingsStore
    private let pollingInterval: TimeInterval
    private let activity: PollingActivity
    private var lastChangeCount: Int
    private var timer: Timer?
    private var isEnabled = false
    private var isSuspended = false
    private var settingsObserver: AnyCancellable?
    private var activityObservers: [AnyCancellable] = []
    private var copyFeedbackGeneration = 0

    public convenience init() {
        self.init(pasteboard: .general, settings: .shared)
    }

    init(
        pasteboard: NSPasteboard,
        settings: SettingsStore,
        pollingInterval: TimeInterval = 1,
        activity: PollingActivity? = nil
    ) {
        self.pasteboard = pasteboard
        self.settings = settings
        self.activity = activity ?? .shared
        self.pollingInterval = max(0.25, pollingInterval)
        lastChangeCount = pasteboard.changeCount

        settingsObserver = settings.$clipboardHistoryEnabled
            .removeDuplicates()
            .sink { [weak self] enabled in
                self?.setEnabled(enabled)
            }
        // Like the other poll loops, the timer stops while nobody can see the result (displays or
        // system asleep, session resigned) and stretches in Low Power Mode.
        activityObservers = [
            self.activity.$isSuspended.removeDuplicates().sink { [weak self] suspended in
                guard let self else { return }
                self.isSuspended = suspended
                self.updateTimer()
                // Catch a copy made while polling was off.
                if !suspended, self.isEnabled { self.scanNow() }
            },
            self.activity.$isLowPowerMode.removeDuplicates().sink { [weak self] _ in
                self?.updateTimer()
            }
        ]
    }

    /// Internal so tests can assert the timer follows the setting and the sleep gate.
    var isPolling: Bool { timer != nil }

    /// Internal so deterministic tests can drive a scan without waiting for a timer.
    func scanNow() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard settings.clipboardHistoryEnabled else { return }

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.privateTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= Self.maxTextBytes
        else { return }

        var updated = entries.filter { $0.text != text }
        updated.insert(ClipboardEntry(text: text), at: 0)
        entries = Array(updated.prefix(Self.maxEntries))
    }

    public func copy(_ id: UUID) {
        guard let entry = entries.first(where: { $0.id == id }) else { return }
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        // Do not ingest our own copy as a new history event on the next timer tick.
        lastChangeCount = pasteboard.changeCount

        var updated = entries.filter { $0.id != id }
        updated.insert(entry, at: 0)
        entries = updated
        copiedEntryID = id
        copyFeedbackGeneration += 1
        let generation = copyFeedbackGeneration
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            MainActor.assumeIsolated {
                guard self?.copyFeedbackGeneration == generation else { return }
                self?.copiedEntryID = nil
            }
        }
    }

    public func remove(_ id: UUID) {
        entries.removeAll { $0.id == id }
        if copiedEntryID == id { copiedEntryID = nil }
    }

    public func clear() {
        entries.removeAll()
        copiedEntryID = nil
    }

    private func setEnabled(_ enabled: Bool) {
        isEnabled = enabled
        lastChangeCount = pasteboard.changeCount
        if !enabled { clear() }
        updateTimer()
    }

    private func updateTimer() {
        timer?.invalidate()
        timer = nil
        guard isEnabled, !isSuspended else { return }

        let interval = activity.scaled(pollingInterval)
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.scanNow() }
        }
        timer.tolerance = min(0.25, interval / 4)
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    deinit {
        timer?.invalidate()
    }
}
