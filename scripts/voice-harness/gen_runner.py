#!/usr/bin/env python3
"""Generates main.swift for the stub-XCTest harness.

Scans every *.swift file under a directory for `class X: XCTestCase` declarations (and
`extension X`) and the `func testY()` methods that follow them, then emits a runner that
instantiates each class per test, calls setUp/tearDown, runs the test, and prints one line per
test plus a summary. Exit status is 1 when any test failed.

usage: gen_runner.py <tests-dir> > main.swift
"""
import re
import sys
from pathlib import Path

CLASS_RE = re.compile(r"^\s*(?:@\w+(?:\([^)]*\))?\s+)*(?:public\s+|internal\s+)?(?:final\s+)?class\s+(\w+)\s*:\s*([\w\s,.]+?)\s*\{?\s*$")
EXT_RE = re.compile(r"^\s*extension\s+(\w+)\b")
OTHER_TYPE_RE = re.compile(r"^(?:@\w+\s+)*(?:final\s+|public\s+|internal\s+|private\s+|fileprivate\s+)*(?:class|struct|enum|actor)\s+\w+")
FUNC_RE = re.compile(r"^\s*(?:@\w+\s+)*func\s+(test\w*)\s*\(\s*\)\s*(async\s+)?(throws\s+)?(?:->\s*\w+\s*)?\{?")


def main() -> int:
    root = Path(sys.argv[1])
    classes: dict[str, list[tuple[str, bool, bool]]] = {}
    known_xctest: set[str] = set()
    files = sorted(p for p in root.rglob("*.swift") if p.name != "main.swift")
    # Pass 1: which classes derive (directly) from XCTestCase.
    for path in files:
        for line in path.read_text().splitlines():
            m = CLASS_RE.match(line)
            if m and "XCTestCase" in m.group(2):
                known_xctest.add(m.group(1))
    # Pass 2: collect tests per class.
    for path in files:
        current = None
        for line in path.read_text().splitlines():
            m = CLASS_RE.match(line)
            if m:
                current = m.group(1) if m.group(1) in known_xctest else None
                continue
            m = EXT_RE.match(line)
            if m:
                current = m.group(1) if m.group(1) in known_xctest else None
                continue
            if OTHER_TYPE_RE.match(line):
                current = None
                continue
            m = FUNC_RE.match(line)
            if m and current:
                tests = classes.setdefault(current, [])
                entry = (m.group(1), bool(m.group(2)), bool(m.group(3)))
                if entry[0] not in [t[0] for t in tests]:
                    tests.append(entry)

    out = []
    out.append("// GENERATED by scripts/voice-harness/gen_runner.py - do not edit.")
    out.append("import Foundation")
    out.append("import XCTest")
    out.append("")
    out.append('let harness = HarnessRunner(filter: ProcessInfo.processInfo.environment["TEST_FILTER"])')
    total = 0
    for cls in sorted(classes):
        for name, is_async, is_throws in classes[cls]:
            total += 1
            if is_async:
                call = f"try await $0.{name}()" if is_throws else f"await $0.{name}()"
                out.append(f'harness.runAsync({cls}.self, "{name}") {{ {call} }}')
            else:
                call = f"try test.{name}()" if is_throws else f"test.{name}()"
                out.append(f'harness.runSync({cls}.self, "{name}") {{ test in try MainActor.assumeIsolated {{ {call} }} }}')
    out.append("")
    out.append("exit(harness.finish())")
    sys.stdout.write("\n".join(out) + "\n")
    sys.stderr.write(f"gen_runner: {len(classes)} classes, {total} tests\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
